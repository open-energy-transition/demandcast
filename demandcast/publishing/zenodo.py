"""
License: AGPL-3.0.

Description:

    This module publishes a release of DemandCast on Zenodo: the trained
    model, its settings and its forecasts, as a new version of a record,
    so that the DOI of all the versions stays the same. The retrieved
    data is not published, since the licences of many data sources do
    not allow it.

    The new version is left as a draft, without the files of the
    previous version, which stay in it, for its user to check and
    publish on the website of Zenodo. A record can also be created, with
    the creators and contributors of a metadata file in the config
    folder (oet_zenodo_metadata.yaml for those of Open Energy
    Transition).

    The files are uploaded to the bucket of the draft, which takes large
    files. The API key is read from ZENODO_API_KEY, or from
    SANDBOX_ZENODO_API_KEY for the sandbox of Zenodo, which can be used
    to test a release. It is sent in the Authorization header, only to
    the address of Zenodo, and a failed request is reported without the
    message of requests, which may show what it sent.
"""

import json
import logging
import os
from typing import Any

import pandas as pd
import requests
import yaml

import utils.config
import utils.paths

# The address of the API of the depositions of Zenodo, with "sandbox."
# for its sandbox.
ZENODO_API = "https://{sandbox}zenodo.org/api/deposit/depositions"

# The title and description of a new record of the forecasts.
TITLE = "Global Dataset of Forecasted Hourly Electricity Demand"
DESCRIPTION = (
    "<p>This dataset contains forecasted hourly electricity demand for "
    "countries and subdivisions, and the trained model that forecasts "
    "it.</p>\n"
    "<p>The forecasts are generated by DemandCast, with a machine learning "
    "model trained on historical electricity demand, weather data and "
    "socioeconomic indicators. The code is in the GitHub repository "
    '<a href="https://github.com/open-energy-transition/demandcast">'
    "https://github.com/open-energy-transition/demandcast</a>.</p>"
)


class ZenodoError(RuntimeError):
    """Error returned by the Zenodo API."""


class ZenodoApi:
    """The requests to the depositions of the API of Zenodo."""

    def __init__(self, sandbox: bool) -> None:
        """
        Set up the address and the key of the API.

        Parameters
        ----------
        sandbox : bool
            Whether to use the sandbox of Zenodo, with the key in
            SANDBOX_ZENODO_API_KEY, instead of Zenodo, with the key in
            ZENODO_API_KEY.
        """
        self.url = ZENODO_API.format(sandbox="sandbox." if sandbox else "")
        self.origin = "https://{sandbox}zenodo.org/".format(
            sandbox="sandbox." if sandbox else ""
        )
        self.access_token = utils.config.read_api_key(
            "SANDBOX_ZENODO_API_KEY" if sandbox else "ZENODO_API_KEY",
            "the sandbox of Zenodo" if sandbox else "Zenodo",
        )

    def request(
        self,
        method: str,
        url: str,
        expected_status: int,
        action: str,
        timeout: int = 60,
        **kwargs: Any,
    ) -> requests.Response:
        """
        Send a request to the API and check its status.

        Parameters
        ----------
        method : str
            The method, "GET", "POST", "PUT" or "DELETE".
        url : str
            The path after the address of the depositions, or a full
            address that the API gave, such as that of a bucket.
        expected_status : int
            The status of a success.
        action : str
            The action of the request, for the message of its failure.
        timeout : int, optional
            The timeout of the request in seconds.
        **kwargs : Any
            The other arguments of the request, such as its data.

        Returns
        -------
        requests.Response
            The response.

        Raises
        ------
        ZenodoError
            If the address is not that of Zenodo, if the request fails,
            or if the status of the response is not the expected one.
        """
        full_url = url if url.startswith("https://") else self.url + url
        if not full_url.startswith(self.origin):
            raise ZenodoError(
                f"Zenodo {action} failed: the address is not that of "
                f"Zenodo ({self.origin})."
            )
        try:
            response = requests.request(
                method,
                full_url,
                headers={
                    **kwargs.pop("headers", {}),
                    "Authorization": f"Bearer {self.access_token}",
                },
                timeout=timeout,
                **kwargs,
            )
        except requests.RequestException as error:
            # The message of the error is left out, and so is the error
            # in the traceback, since they may show the request.
            raise ZenodoError(
                f"Zenodo {action} failed: {type(error).__name__}."
            ) from None
        if response.status_code != expected_status:
            raise ZenodoError(
                f"Zenodo {action} failed ({response.status_code}): "
                f"{response.text}"
            )
        return response


def build_metadata(metadata_file: str, version: str) -> dict:
    """
    Build the metadata of a new record of the forecasts.

    Parameters
    ----------
    metadata_file : str
        The name of the file in the config folder with the creators and
        contributors.
    version : str
        The version of the release, such as "1.1.0".

    Returns
    -------
    dict
        The metadata, as the API of Zenodo takes it.
    """
    with open(
        utils.paths.get_config_file(metadata_file), encoding="utf-8"
    ) as file:
        people = yaml.safe_load(file)
    return {
        "title": TITLE,
        "upload_type": "dataset",
        "description": DESCRIPTION,
        "creators": people["creators"],
        "contributors": people.get("contributors", []),
        "access_right": "open",
        "license": "cc-by-4.0",
        "keywords": [
            "electricity demand",
            "forecasts",
            "machine learning",
        ],
        "related_identifiers": [
            {
                "relation": "isDerivedFrom",
                "identifier": (
                    "https://github.com/open-energy-transition/demandcast"
                ),
                "resource_type": "software",
            }
        ],
        "version": version,
        "language": "eng",
    }


def _create_draft(
    api: ZenodoApi, record: int | None, metadata_file: str, version: str
) -> dict:
    """
    Create the draft of a new version of a record, or of a new record.

    Parameters
    ----------
    api : ZenodoApi
        The API of Zenodo.
    record : int | None
        The number of a version of the record, or None for a new record.
    metadata_file : str
        The file of the creators and contributors of a new record.
    version : str
        The version of the release.

    Returns
    -------
    dict
        The draft, as the API of Zenodo gives it.
    """
    if record is None:
        return api.request(
            "POST",
            "",
            201,
            "record creation",
            data=json.dumps(
                {"metadata": build_metadata(metadata_file, version)}
            ),
            headers={"Content-Type": "application/json"},
        ).json()

    new_version = api.request(
        "POST", f"/{record}/actions/newversion", 201, "new version creation"
    ).json()
    draft = api.request(
        "GET", new_version["links"]["latest_draft"], 200, "draft retrieval"
    ).json()

    # The draft has the files of the previous version, which keeps them:
    # the new version has only the files of the release.
    for file_info in draft.get("files", []):
        api.request(
            "DELETE",
            f"/{draft['id']}/files/{file_info['id']}",
            204,
            f"removal of {file_info['filename']} from the draft",
        )

    metadata = {
        key: value
        for key, value in draft["metadata"].items()
        if key not in ("doi", "prereserve_doi")
    }
    metadata["version"] = version
    metadata["publication_date"] = pd.Timestamp.now().strftime("%Y-%m-%d")
    return api.request(
        "PUT",
        f"/{draft['id']}",
        200,
        "metadata update",
        data=json.dumps({"metadata": metadata}),
        headers={"Content-Type": "application/json"},
    ).json()


def publish_release(
    file_paths: list[str],
    version: str,
    record: int | None,
    metadata_file: str = "oet_zenodo_metadata.yaml",
    sandbox: bool = False,
) -> str:
    """
    Upload the files of a release as a draft on Zenodo.

    Parameters
    ----------
    file_paths : list[str]
        The paths of the files: the trained model, its settings and its
        forecasts.
    version : str
        The version of the release, such as "1.1.0".
    record : int | None
        The number of a version of the record whose new version is the
        release, or None to create a record.
    metadata_file : str, optional
        The file of the creators and contributors of a new record, in
        the config folder.
    sandbox : bool, optional
        Whether to use the sandbox of Zenodo.

    Returns
    -------
    str
        The address of the draft, to check and publish it.

    Raises
    ------
    FileNotFoundError
        If a file does not exist.
    ValueError
        If two files have the same name.
    """
    for file_path in file_paths:
        if not os.path.isfile(file_path):
            raise FileNotFoundError(f"The file {file_path} does not exist.")
    names = [os.path.basename(file_path) for file_path in file_paths]
    if len(set(names)) < len(names):
        raise ValueError(f"The files have the same names: {names}.")

    api = ZenodoApi(sandbox)
    draft = _create_draft(api, record, metadata_file, version)

    for file_path, name in zip(file_paths, names, strict=True):
        logging.info(f"Uploading {file_path} to the draft {draft['id']}.")
        with open(file_path, "rb") as file:
            api.request(
                "PUT",
                f"{draft['links']['bucket']}/{name}",
                201,
                f"upload of {file_path}",
                # Zenodo answers once it has received the whole file.
                timeout=3600,
                data=file,
            )

    draft_url = draft["links"]["html"]
    logging.info(
        f"The release {version} is a draft on Zenodo: check and publish "
        f"it at {draft_url}."
    )
    return draft_url
