import datetime
import os
from collections.abc import Mapping

import cartopy.crs
import cartopy.feature
import matplotlib.cm
import matplotlib.colors
import matplotlib.pyplot as plt
import utils.data_sources
import utils.shapes

# The classes of the years of available data, with their upper bounds.
YEAR_CLASSES = {"0-4": 5, "5-9": 10, "10-19": 20, "20+": float("inf")}


def get_classes_of_years(
    date_ranges: Mapping[str, tuple[datetime.date, datetime.date]],
) -> dict[str, int]:
    """
    Get the class of the years of available data of each code.

    Parameters
    ----------
    date_ranges : Mapping[str, tuple[datetime.date, datetime.date]]
        The first and last dates of the data of each country or
        subdivision.

    Returns
    -------
    dict[str, int]
        The class of each code, the position of the first class of
        YEAR_CLASSES whose upper bound is above its years of data, of
        365 days.
    """
    return {
        code: next(
            number
            for number, upper_bound in enumerate(YEAR_CLASSES.values())
            if (end - start).days / 365 < upper_bound
        )
        for code, (start, end) in date_ranges.items()
    }


def plot(figure_directory: str) -> None:
    """
    Plot a map of the countries and subdivisions.

    This function generates a map showing the countries and subdivisions
    for which retrieval scripts of electricity demand data are
    available. The shapes of standard countries and subdivisions are
    taken from the Natural Earth database. The shapes of non-standard
    countries and subdivisions are taken from the shapes generated by
    the respective scripts.

    Parameters
    ----------
    figure_directory : str
        The directory to store the figure.
    """
    # Get the class of the years of available data of all countries
    # and subdivisions.
    date_ranges = utils.data_sources.read_all_date_ranges()
    classes_of_years = get_classes_of_years(
        {
            code: date_ranges[code]
            for code in utils.data_sources.read_all_codes_with_electricity_demand_data()
        }
    )

    # Define the map projection and the coordinate reference system of
    # the data to plot.
    map_projection = cartopy.crs.Robinson(central_longitude=0)
    data_crs = cartopy.crs.PlateCarree()

    # Define the colormap.
    map_cmap = plt.get_cmap("Blues")

    # Define the extent of the colormap.
    lower_bound = 0.2
    upper_bound = 0.9

    # Define the transparency of the shapes.
    alpha = 0.8

    # Initialize the figure.
    fig, ax = plt.subplots(
        figsize=(12, 16), subplot_kw={"projection": map_projection}
    )

    # Plot the land and the ocean. cartopy has no type information, so
    # mypy does not know that ax is a cartopy GeoAxes.
    ax.add_feature(  # type: ignore[attr-defined]
        cartopy.feature.LAND, facecolor="lightgray"
    )
    ax.add_feature(  # type: ignore[attr-defined]
        cartopy.feature.OCEAN, facecolor="white"
    )

    # The colors of the classes.
    base_colors = [
        map_cmap(lower_bound + number * (upper_bound - lower_bound) / 3)
        for number in range(len(YEAR_CLASSES))
    ]

    # Loop over the countries.
    for code, class_of_years in classes_of_years.items():
        # Get the shape of the country or subdivision.
        entity_shape = utils.shapes.get_entity_shape(code, make_plot=False)
        color = base_colors[class_of_years]

        # Plot the country or subdivision.
        entity_shape.plot(
            ax=ax,
            transform=data_crs,
            facecolor=color,
            edgecolor="black",
            linewidth=0.5,
            aspect=None,
            autolim=False,
            alpha=alpha,
        )

    # Give the colors of the colorbar the transparency of the shapes.
    base_colors = [(*color[:3], alpha) for color in base_colors]

    # Add a colorbar.
    bar_cmap = matplotlib.colors.ListedColormap(base_colors, name="bar_cmap")
    bounds = [0, 1, 2, 3, 4]
    norm = matplotlib.colors.BoundaryNorm(bounds, bar_cmap.N)
    cbar = fig.colorbar(
        matplotlib.cm.ScalarMappable(norm=norm, cmap=bar_cmap),
        ax=ax,
        orientation="horizontal",
        pad=0.025,
        shrink=0.5,
        ticks=[0.5, 1.5, 2.5, 3.5],
    )
    cbar.ax.set_xticklabels(list(YEAR_CLASSES))
    cbar.ax.tick_params(labelsize=12)

    # Add a label to the colorbar for the figure.
    cbar.set_label(
        "Years of available data",
        fontsize=14,
        weight="bold",
        labelpad=10,
    )

    # Add the title for the Awesome-Electricity-Demand repository.
    url = ax.text(
        0.5,
        1.21,
        "https://github.com/open-energy-transition/Awesome-Electricity-Demand",
        fontsize=12,
        ha="center",
        weight="bold",
        transform=ax.transAxes,
        color="tab:blue",
    )
    aed_title = plt.text(
        0.5,
        1.05,
        "Countries and subdivisions with publicly available\nhigh-resolution electricity demand data",
        fontsize=18,
        ha="center",
        weight="bold",
        transform=ax.transAxes,
    )

    # Save the figure with the title for Awesome-Electricity-Demand.
    fig.savefig(
        os.path.join(figure_directory, "available_entities_for_aed.png"),
        dpi=300,
        bbox_inches="tight",
    )

    url.set_visible(False)
    aed_title.set_visible(False)

    # Add the title for the DemandCast repository.
    ax.set_title(
        (
            "Countries and subdivisions for which retrieval modules\n"
            "of electricity demand data are available"
        ),
        fontsize=18,
        y=1.04,
        weight="bold",
    )

    # Save the figure with the title for DemandCast.
    fig.savefig(
        os.path.join(figure_directory, "available_entities.png"),
        dpi=300,
        bbox_inches="tight",
    )

    # Save the figure without the background color in the light mode.
    fig.savefig(
        os.path.join(figure_directory, "available_entities_light_mode.png"),
        dpi=300,
        bbox_inches="tight",
        transparent=True,
    )

    # Change the color of all the text to white.
    ax.title.set_color("white")
    for tick in cbar.ax.get_xticklabels():
        tick.set_color("white")
    cbar.ax.xaxis.label.set_color("white")

    # Save the figure without the background color in the dark mode.
    fig.savefig(
        os.path.join(figure_directory, "available_entities_dark_mode.png"),
        dpi=300,
        bbox_inches="tight",
        transparent=True,
    )
